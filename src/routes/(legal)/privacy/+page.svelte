	<!-- 1. Introduction -->
	<section id="introduction">
		<h2>1. Introduction</h2>
		<p>
			DigitalDSA Technologies Private Limited ("DigitalDSA", "we", "us", or "our") operates the
			DigitalDSA platform at <strong>digitaldsa.com</strong> and associated mobile applications.
		</p>
		<p>
			DigitalDSA is a <strong>B2B (business-to-business) intelligence platform</strong> designed exclusively
			for Direct Selling Agents (DSAs), loan brokers, Corporate DSAs, and Bank Relationship Managers (RMs)
			in India. We are not a lender, financial institution, or consumer-facing loan marketplace.
		</p>
		<p>
			This Privacy Policy explains how we collect, use, store, and protect information when you use
			our platform. By accessing or using DigitalDSA, you agree to the practices described in this
			policy.
		</p>
	</section>

	<!-- 2. Information We Collect -->
	<section id="information-we-collect">
		<h2>2. Information We Collect</h2>

		<h3>2.1 Account Information</h3>
		<p>When you register and use DigitalDSA, we collect:</p>
		<ul>
			<li><strong>Mobile number</strong> — required for authentication via OTP</li>
			<li><strong>Name and professional details</strong> — provided during DSA/RM onboarding</li>
			<li><strong>Email address</strong> — optional, for notifications and communication</li>
			<li>
				<strong>RERA registration number</strong> — if applicable to your professional practice
			</li>
			<li><strong>Company/firm name and address</strong> — for business profile verification</li>
		</ul>

		<h3>2.2 Device and Technical Information</h3>
		<p>We automatically collect:</p>
		<ul>
			<li>
				<strong>Device fingerprint</strong> — a hashed identifier derived from your device's hardware
				and software characteristics, used for session security and single-device enforcement
			</li>
			<li>
				<strong>IP address</strong> — for geographic verification (India-only service) and security
			</li>
			<li><strong>Browser type and version</strong></li>
			<li><strong>Operating system</strong></li>
			<li><strong>Screen resolution and hardware characteristics</strong></li>
		</ul>

		<h3>2.3 Client Financial Data</h3>
		<p>
			When you use the loan evaluation features, you enter financial data about your clients. See <a
				href="#client-financial-data">Section 5</a
			> for detailed handling of this data.
		</p>

		<h3>2.4 Usage Data</h3>
		<p>We collect information about how you interact with the platform:</p>
		<ul>
			<li>Pages visited and features used</li>
			<li>Form submission and evaluation history</li>
			<li>Lender selection and comparison activity</li>
			<li>Session timestamps and duration</li>
		</ul>
	</section>

