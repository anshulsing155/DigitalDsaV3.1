	<!-- 5. Client Financial Data -->
	<section id="client-financial-data">
		<h2>5. Client Financial Data</h2>
		<p>
			This section addresses how we handle the financial data you enter about your clients (loan
			applicants).
		</p>

		<h3>5.1 No Required PII</h3>
		<p>
			DigitalDSA is designed so that <strong
				>no personally identifiable information (PII) about loan applicants is required</strong
			> to use the evaluation engine. Client name, PAN, Aadhaar, phone number, and address are never mandatory
			fields. An optional contact field exists for your convenience but is not used in eligibility calculations.
		</p>

		<h3>5.2 Financial Data Handling</h3>
		<p>Client financial data (income profiles, loan amounts, property values, credit scores) is:</p>
		<ul>
			<li>
				Stored as <strong>immutable versioned snapshots</strong> — edits create new versions, not overwrites,
				maintaining a complete audit trail
			</li>
			<li>
				Processed server-side only — calculations and eligibility rules execute on our servers,
				never in the browser
			</li>
			<li>Encrypted in transit (TLS 1.2+) and at rest</li>
			<li>Accessible only to the authenticated DSA who created the case</li>
		</ul>

		<h3>5.3 Review PDF Privacy</h3>
		<p>
			Review PDFs generated by the platform <strong>never contain PII</strong> by system design. This
			is enforced at the server level and cannot be overridden.
		</p>
	</section>

	<!-- 6. Cookies & Storage -->
	<section id="cookies-storage">
		<h2>6. Cookies &amp; Local Storage</h2>
		<p>We use the following storage mechanisms:</p>

		<h3>6.1 Cookies</h3>
		<ul>
			<li>
				<strong>Authentication tokens</strong> (httpOnly, secure) — JWT access token (15-minute expiry)
				and refresh token (30-day expiry) for maintaining your session
			</li>
			<li><strong>Active role</strong> — stores your current role (DSA/RM/Admin) for routing</li>
			<li><strong>CSRF token</strong> — for protection against cross-site request forgery</li>
		</ul>

		<h3>6.2 Session Storage</h3>
		<p>
			We use browser sessionStorage for temporary form data during active sessions. This data is
			automatically cleared when you close the browser tab.
		</p>

		<h3>6.3 Analytics</h3>
		<p>
			We use Google Analytics and Microsoft Clarity to understand platform usage patterns. These
			services may set their own cookies. You can opt out of Google Analytics at
			<a href="https://tools.google.com/dlpage/gaoptout" target="_blank" rel="noopener noreferrer"
				>tools.google.com/dlpage/gaoptout</a
			>.
		</p>
	</section>

