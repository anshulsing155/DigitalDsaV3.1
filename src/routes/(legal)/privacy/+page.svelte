	<!-- 8. Data Security -->
	<section id="data-security">
		<h2>8. Data Security</h2>
		<p>We implement the following security measures:</p>
		<ul>
			<li><strong>Encryption in transit</strong> — all data is transmitted over TLS 1.2+</li>
			<li><strong>Encryption at rest</strong> — database storage is encrypted</li>
			<li>
				<strong>Single-device enforcement</strong> — only one active session per account at a time
			</li>
			<li>
				<strong>Device fingerprinting</strong> — sessions are bound to specific devices to detect unauthorized
				access
			</li>
			<li>
				<strong>JWT authentication</strong> — short-lived access tokens (15 minutes) with secure refresh
				mechanism
			</li>
			<li>
				<strong>CSRF protection</strong> — all state-changing requests are protected against cross-site
				request forgery
			</li>
			<li><strong>Content Security Policy</strong> — strict CSP headers to prevent XSS attacks</li>
			<li>
				<strong>IP geolocation verification</strong> — access restricted to Indian IP addresses
			</li>
			<li><strong>Rate limiting</strong> — protection against brute-force and automated attacks</li>
		</ul>
		<p>
			While we take security seriously, no method of electronic transmission or storage is 100%
			secure. We cannot guarantee absolute security but strive to use commercially acceptable means
			to protect your data.
		</p>
	</section>

