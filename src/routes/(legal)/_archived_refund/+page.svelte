		<h2>1. Overview</h2>
		<p>
			DigitalDSA Technologies Private Limited ("DigitalDSA", "we", "us", or "our") offers
			subscription-based services to Direct Selling Agents (DSAs) and financial professionals
			through the DigitalDSA platform at <strong>digitaldsa.com</strong> and associated mobile applications.
		</p>
