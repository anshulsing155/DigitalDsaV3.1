			All payments are processed securely through <strong>Razorpay</strong>, a PCI DSS compliant
			payment gateway. We do not store your payment card details on our servers.
		</p>
		<p>
			This Refund Policy outlines our practices regarding refunds, cancellations, and subscription
			management. By subscribing to DigitalDSA, you agree to the terms described in this policy.
		</p>
	</section>

	<!-- 2. Subscription Plans -->
	<section id="subscription-plans">
		<h2>2. Subscription Plans</h2>
		<p>DigitalDSA services are offered on the following basis:</p>
		<ul>
			<li><strong>Free tier</strong> — available to all registered users with limited features</li>
			<li><strong>Monthly subscription</strong> — billed on a recurring monthly cycle</li>
			<li><strong>Annual subscription</strong> — billed on a recurring annual cycle</li>
		</ul>
		<p>
			Paid tiers unlock full access to evaluation, comparison, and file-building capabilities that
			form the core of the DigitalDSA platform.
		</p>
		<p>
			All pricing is displayed in <strong>INR (Indian Rupees)</strong> and is inclusive of applicable
			taxes.
		</p>
	</section>

	<!-- 3. Refund Eligibility -->
	<section id="refund-eligibility">
		<h2>3. Refund Eligibility</h2>

		<h3>3.1 Full Refund</h3>
		<p>
			A full refund is available within <strong>7 days</strong> of your first subscription purchase, provided:
		</p>
		<ul>
			<li>No evaluation or comparison features were used substantially during the period</li>
		</ul>

		<h3>3.2 Partial Refund (Prorated)</h3>
		<p>A prorated partial refund may be issued if:</p>
		<ul>
			<li>
				The service was significantly unavailable, defined as more than <strong
					>48 hours of cumulative downtime</strong
				> within a single billing period
			</li>
		</ul>

		<h3>3.3 No Refund</h3>
		<p>Refunds will <strong>not</strong> be issued in the following cases:</p>
		<ul>
			<li>Services have been used during the billing period</li>
			<li>Account termination due to violation of our Terms of Service</li>
			<li>Change of mind after the 7-day window from first purchase</li>
		</ul>
	</section>

	<!-- 4. How to Request a Refund -->
	<section id="how-to-request">
		<h2>4. How to Request a Refund</h2>
		<p>
			To request a refund, please email us at
			<a href="mailto:billing@digitaldsa.com">billing@digitaldsa.com</a> with the following details:
		</p>
		<ul>
			<li>
				<strong>Registered mobile number</strong> — the phone number associated with your DigitalDSA account
			</li>
			<li>
				<strong>Subscription details</strong> — your plan type, billing date, and transaction ID (if available)
			</li>
			<li>
				<strong>Reason for refund</strong> — a brief explanation of why you are requesting a refund
			</li>
		</ul>
		<p>
			We will <strong>acknowledge your request within 2 business days</strong> and provide a
			resolution within <strong>7 business days</strong> of acknowledgment.
		</p>
	</section>

	<!-- 5. Refund Processing -->
	<section id="refund-processing">
		<h2>5. Refund Processing</h2>
		<p>Once a refund is approved:</p>
		<ul>
			<li>
				<strong>Method</strong> — refunds are processed via Razorpay to the
				<strong>original payment method</strong> used for the transaction
			</li>
			<li>
				<strong>Processing time</strong> — 5 to 10 business days, depending on your bank or payment provider
			</li>
			<li>
				<strong>Currency</strong> — all refund amounts will be in
				<strong>INR (Indian Rupees)</strong>
			</li>
			<li>
				<strong>Bank charges</strong> — any charges levied by your bank for processing the refund are
				borne by the user
			</li>
		</ul>
		<p>
			You will receive a confirmation email once the refund has been initiated from our end. Please
			contact your bank if the refund does not reflect within the stated timeframe.
		</p>
	</section>

	<!-- 6. Cancellation -->
	<section id="cancellation">
		<h2>6. Cancellation</h2>
		<p>
			You may cancel your subscription at any time from your <strong>dashboard settings</strong>.
		</p>
		<ul>
			<li>
				<strong>Effective date</strong> — cancellation takes effect at the end of the current billing
				period
			</li>
			<li>
				<strong>Continued access</strong> — you retain access to all paid features until the end of the
				billing period you have already paid for
			</li>
			<li>
				<strong>No partial refund</strong> — there is no refund for the unused portion of the
				current billing period, except as covered under
				<a href="#refund-eligibility">Section 3 (Refund Eligibility)</a>
			</li>
		</ul>
		<p>
			After cancellation takes effect, your account will revert to the free tier with limited
			features. Your data will be retained in accordance with our
			<a href="/privacy#data-retention">Privacy Policy</a>.
		</p>
	</section>

